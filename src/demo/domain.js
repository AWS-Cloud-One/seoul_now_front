    dLat = (place.lat - origin.lat) * rad,
    dLon = (place.lon - origin.lon) * rad
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(place.lat * rad) * Math.cos(origin.lat * rad) * Math.sin(dLon / 2) ** 2
  return 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(Math.max(0, 1 - a)))
