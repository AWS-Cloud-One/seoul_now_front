function conditionChanges(a, b) {
  const labels = {
    departure: '출발지',
    purposes: '목적',
    keyword: '키워드',
    group: '동행',
    ages: '연령대',
    headcount: '인원',
    maxMinutes: '최대 운전 시간',
  }
  const fmt = (k, v) =>
    v === null || v === '' || (Array.isArray(v) && !v.length)
      ? k === 'maxMinutes'
        ? '제한 없음'
        : '선택 안 함'
      : Array.isArray(v)
        ? v.join(' 또는 ')
        : `${v}${k === 'headcount' ? '명' : k === 'maxMinutes' ? '분' : ''}`
  return Object.keys(labels)
    .filter((k) => JSON.stringify(a[k]) !== JSON.stringify(b[k]))
    .map((k) => `${labels[k]}: ${fmt(k, a[k])} → ${fmt(k, b[k])}`)
}
